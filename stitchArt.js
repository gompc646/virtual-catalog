function renderStitchArt(containerId, motifKey) {
  const container = document.getElementById(containerId);
  if (!container) return;
  const motif = stitchMotifs[motifKey];
  if (!motif) return;
  let out = "";
  for (let y = 0; y < motif.length; y++) {
    for (let x = 0; x < motif[y].length; x++) {
      out += motif[y][x] === 1 ? "x" : " ";
    }
    out += "\n";
  }
  container.textContent = out;
}

